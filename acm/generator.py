def _mask(text: str, key: list[int]) -> list[int]:
    return [(ord(ch) ^ key[i & 7]) for i, ch in enumerate(text)] + [key[len(text) & 7]]


def _main(comp: Composition, rng: random.Random) -> str:
    prompt = _PROMPTS.get(comp.format, DEFAULT_PROMPT)
    if not comp.features.encrypt_strings:
        return (
            _PLAIN_MAIN.replace("__PROMPT__", prompt)
            .replace("__OK__", OK_TEXT)
            .replace("__BAD__", BAD_TEXT)
        )

    key = [rng.randrange(1, 256) for _ in range(8)]
    template = _MASKED_MAIN
    template = template.replace("__PROMPT__", _c_bytes(_mask(prompt, key), indent=""))
    template = template.replace("__OK__", _c_bytes(_mask(OK_TEXT, key), indent=""))
    template = template.replace("__BAD__", _c_bytes(_mask(BAD_TEXT, key), indent=""))
    return template


